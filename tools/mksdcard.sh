#!/bin/sh
# Assemble the SD card image for a real Raspberry Pi 4 (partition 1 FAT32 boot files, partition 2 HFS+ root).
#
#   tools/mksdcard.sh OUT.img ROOT.img [OUTDIR]
#
# OUTDIR (default build/qemu-pi4) is where tools/pi4-qemu-boot.sh left loader.elf and payload.bin; build the
# payload with SDPART=2 and SDIMG=<any image> so the command line roots on sdroot0 partition 2. Pi firmware
# files (start4.elf, fixup4.dat, bcm2711-rpi-4-b.dtb) come from FIRMWARE_DIR if set, else are downloaded from
# raspberrypi/firmware at FIRMWARE_TAG. OBJCOPY defaults to aarch64-linux-gnu-objcopy.
# Not verified on hardware: only the layout is (fsck.fat, and the same partition 2 boots on QEMU).
set -eu
OUT=${1:?usage: $0 OUT.img ROOT.img [OUTDIR]}
ROOT=${2:?usage: $0 OUT.img ROOT.img [OUTDIR]}
HERE=$(cd "$(dirname "$0")/.." && pwd)
BOOTOUT=${3:-$HERE/build/qemu-pi4}
OBJCOPY=${OBJCOPY:-aarch64-linux-gnu-objcopy}
FIRMWARE_TAG=${FIRMWARE_TAG:-1.20250430}
W=$(mktemp -d)
trap 'rm -rf "$W"' EXIT

$OBJCOPY -O binary "$BOOTOUT/loader.elf" "$W/kernel8.img"
PA=$(cat "$BOOTOUT/payload.pa")
cat > "$W/config.txt" <<CFG
# Raspberry Pi 4 boot of xnu-bcm2711 (generated by tools/mksdcard.sh)
arm_64bit=1
enable_uart=1
core_freq=250
core_freq_min=250
kernel=kernel8.img
# the loader finds the kernel, device tree and command line packed at PAYLOAD_PA
initramfs payload.bin $(printf 0x%x "$PA")
CFG

set --
for f in start4.elf fixup4.dat bcm2711-rpi-4-b.dtb; do
    if [ -n "${FIRMWARE_DIR:-}" ]; then
        cp "$FIRMWARE_DIR/$f" "$W/$f"
    else
        curl -fsSL -o "$W/$f" "https://github.com/raspberrypi/firmware/raw/$FIRMWARE_TAG/boot/$f"
    fi
    set -- "$@" --boot "$f=$W/$f"
done
python3 "$HERE/tools/mksdimage.py" "$OUT" --root "$ROOT" --boot config.txt="$W/config.txt" \
    --boot kernel8.img="$W/kernel8.img" --boot payload.bin="$BOOTOUT/payload.bin" "$@" \
    --boot-size "${BOOT_SIZE:-128M}" ${PAD_POW2:+--pad-pow2}
